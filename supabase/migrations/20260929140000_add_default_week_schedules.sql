/*
  # Add Default & Recurring Week Support

  ## Overview
  Extends device_week_schedules with a persistent "default week" concept.
  Each device may have exactly one default schedule (week_start IS NULL,
  is_default = true) that acts as the always-visible canvas and carries
  forward to any week without an explicit override. Real weeks that are
  edited become overrides; weeks left untouched inherit the default (or a
  matching recurring week) at read time.

  ## Changes
  - `is_default` (boolean, default false) — marks the device's default week.
  - `week_start` becomes nullable (null only for default rows).
  - Replaces UNIQUE(device_id, week_start) with two partial unique indexes:
    - one default row per device
    - one override row per (device, week_start)
  - CHECK ensures default rows have null week_start and override rows do not.
*/

ALTER TABLE device_week_schedules
  ADD COLUMN IF NOT EXISTS is_default boolean NOT NULL DEFAULT false;

ALTER TABLE device_week_schedules
  ALTER COLUMN week_start DROP NOT NULL;

-- Drop the old full unique constraint (name is auto-generated by Postgres)
ALTER TABLE device_week_schedules
  DROP CONSTRAINT IF EXISTS device_week_schedules_device_id_week_start_key;

-- One default schedule per device
CREATE UNIQUE INDEX IF NOT EXISTS uq_dws_default_per_device
  ON device_week_schedules(device_id)
  WHERE is_default;

-- One override schedule per device per week
CREATE UNIQUE INDEX IF NOT EXISTS uq_dws_week_per_device
  ON device_week_schedules(device_id, week_start)
  WHERE NOT is_default;

-- Default rows carry no week_start; override rows must have one
ALTER TABLE device_week_schedules
  DROP CONSTRAINT IF EXISTS chk_dws_default_week_start;
ALTER TABLE device_week_schedules
  ADD CONSTRAINT chk_dws_default_week_start CHECK (
    (is_default AND week_start IS NULL) OR
    (NOT is_default AND week_start IS NOT NULL)
  );

CREATE INDEX IF NOT EXISTS idx_dws_is_default ON device_week_schedules(device_id) WHERE is_default;
CREATE INDEX IF NOT EXISTS idx_dws_is_recurring ON device_week_schedules(device_id) WHERE is_recurring;
